import whisper
from google.colab import files

def audio_to_text():
  uploaded = files.upload()
  audio_path = next(iter(uploaded))

  model = whisper.load_model('small')
  result = model.transcribe(audio_path)

  print( result['text'] )

"""#Function Call"""

audio_to_text()